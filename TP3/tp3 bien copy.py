#########  Métricas TP1 ##########
# Reutilizamos las funciones de métricas que definimos en el TP1 para evaluar el
# desempeño de los modelos de clasificación (regresión logística y SVM) en el
# conjunto de prueba. Clase positiva: 'APROBADO'.
def calcularPositivosYnegativos(predicciones, esperados):
  TP = 0
  FP = 0
  TN = 0
  FN = 0
  # Recorremos el vector de predicciones y comparamos el resultado con el esperado
  for i in range(len(predicciones)):
      pred = str(predicciones[i]).strip().lower()
      esp = str(esperados[i]).strip().lower()
      if pred == 'aprobado':   # Predicciones POSITIVAS
        if esp == 'aprobado':
          TP += 1
        else:
          FP += 1
      else:                               # Predicciones NEGATIVAS
        if esp == 'reprobado':
          TN += 1
        else:
          FN += 1
  return TP,FP,TN,FN


# Matriz de confusión para un conjunto de predicciones y esperados
def matrizDeConfusion(predicciones, esperados):
  tp, fp, tn, fn = calcularPositivosYnegativos(predicciones, esperados)
  return [[tp, fn], [fp, tn]]

def accuracy(tp, fp, tn, fn):
  return (tp + tn) / (tp + tn + fp + fn)

def recall(tp, fn):
  # Si no hay positivos reales (tp+fn=0), el recall no está definido: se toma 0.
  if tp + fn == 0:
    return 0
  return tp / (tp + fn)

def especificidad(fp, tn):
  if tn + fp == 0:
    return 0
  return tn / (tn + fp)

def precision(tp, fp):
  # Ocurre, por ejemplo, con el kernel sigmoideo, que puede predecir TODOS los
  # casos como negativos (0 positivos predichos) y dejaría tp=fp=0.
  if tp + fp == 0:
    return 0
  return tp / (tp + fp)

def f1_score(tp, fp, fn):
  p = precision(tp, fp)
  r = recall(tp, fn)
  if p + r == 0:
    return 0
  return 2 * (p * r) / (p + r)

def tpr_fpr(tp, fp, tn, fn):
  return tp / (tp + fn), fp / (tn + fp)

def falsePositiveRate(fp, tn):
  if tn + fp == 0:
    return 0
  return fp / (tn + fp)


