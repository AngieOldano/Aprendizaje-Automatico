def calcularCoheficientesBeta(X, y):
    # Calcula los coeficientes beta utilizando la fórmula de mínimos cuadrados.
    # Fórmula: beta = (X^T * X)^(-1) * X^T * y
    return np.linalg.inv(X.T @ X) @ X.T @ y

# Calcular los coeficientes beta
