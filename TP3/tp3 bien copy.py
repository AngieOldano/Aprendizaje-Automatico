def sst(y):
    # Calcula la suma total de cuadrados (SST) para evaluar la variabilidad total en los datos.
    return np.sum((y - np.mean(y)) ** 2)

def ssr(y, y_pred):
    # Calcula la suma de cuadrados de regresión (SSR) para evaluar la variabilidad explicada por el modelo.
    return np.sum((y_pred - np.mean(y)) ** 2)

def sse(y, y_pred):
    # Calcula la suma de cuadrados del error (SSE) para evaluar la variabilidad no explicada por el modelo.
    return np.sum((y - y_pred) ** 2)

def calcularR2(y, y_pred):
    # Calcula el coeficiente de determinación R^2, que indica la proporción de la variabilidad total explicada por el modelo.
    return ssr(y, y_pred) / sst(y)

